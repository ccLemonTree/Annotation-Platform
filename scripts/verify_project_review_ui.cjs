async(page)=>{
  const id='e251de70-5c16-46f4-9cd9-d90a2262539e',checks=[];
  const ensure=(value,name)=>{if(!value)throw Error(name);checks.push(name);};
  const headers={Authorization:'Bearer '+await page.evaluate(()=>localStorage.getItem('token'))};
  const live=await(await page.request.get('http://localhost:3000/api/annotations?project_id='+id,{headers})).json();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://localhost:3000/annotations');
  await page.getByText('标注项目',{exact:true}).waitFor();
  ensure(!await page.getByRole('columnheader',{name:'标注ID',exact:true}).count(),'overview groups by projects without global UUID table');
  const tile=page.getByRole('region',{name:'标注项目 test-img',exact:true});
  await tile.waitFor();
  await tile.getByRole('link',{name:'进入标注与审核',exact:true}).click();
  await page.waitForURL(url=>url.pathname==='/annotations'&&url.searchParams.get('project_id')===id);
  await page.getByRole('columnheader',{name:'图片名称',exact:true}).waitFor();
  await page.getByRole('row').filter({hasText:'20260417170218_25223_1840.jpg'}).waitFor();
  ensure(await page.getByRole('link',{name:'打开标注 / 审核',exact:true}).count()===live.total,'project shows only its latest annotations by filename');
  ensure(!await page.getByRole('columnheader',{name:'资产ID',exact:true}).count(),'image context replaces long IDs');
  const filter=page.getByRole('combobox',{name:'项目审核状态'});
  await filter.fill('待审核');await filter.press('ArrowDown');await filter.press('Enter');
  await page.waitForURL(url=>url.searchParams.get('review_status')==='pending');
  const href=page.url();
  await page.reload();await page.getByRole('link',{name:'打开标注 / 审核',exact:true}).first().waitFor();
  ensure(page.url()===href,'refresh keeps project and review filter');
  await page.getByRole('link',{name:'打开标注 / 审核',exact:true}).first().click();
  await page.getByRole('img',{name:'检测画框区域'}).waitFor();
  const back=page.getByRole('link',{name:'返回 test-img 标注与审核',exact:true});
  await back.waitFor();
  const currentPath=new URL(page.url()).pathname;
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(button=>['上一张','下一张'].includes(button.textContent)&&!button.disabled));
  const next=page.getByRole('button',{name:'下一张',exact:true});
  await (await next.isEnabled()?next:page.getByRole('button',{name:'上一张',exact:true})).click();
  await page.waitForURL(url=>url.pathname!==currentPath&&url.pathname.startsWith('/annotate/')&&url.searchParams.get('from')==='review');
  await back.waitFor();await back.click();
  await page.waitForURL(href);
  ensure(page.url()===href,'workbench image switching retains project review return and filters');
  await page.getByRole('link',{name:'返回标注项目',exact:true}).click();
  await page.getByText('标注项目',{exact:true}).waitFor();
  await page.goBack();await page.getByRole('columnheader',{name:'图片名称',exact:true}).waitFor();
  ensure(new URL(page.url()).searchParams.get('project_id')===id,'browser back restores selected project');
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>parseInt(getComputedStyle(document.querySelector('.platform-main')).marginLeft)===64);
  ensure(await page.locator('html').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'project review has no narrow-screen page overflow');
  await page.screenshot({path:'output/playwright/project-review-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  return {checks,scope:'real projects/latest annotations/images read; no review or annotation writes'};
}
